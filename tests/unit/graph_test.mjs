import { buildGraph, graphStats, findFaces, faceInfo, mergeChains } from './wallgraph.mjs';
const P=(x,y)=>({x,y});
const sq=(x,y,s)=>[P(x,y),P(x+s,y),P(x+s,y+s),P(x,y+s),P(x,y)];
let g=buildGraph([{points:sq(0,0,100),thickness:5}],4);
console.log('single closed square', graphStats(g), findFaces(g,10).map(f=>f.area));
g=buildGraph([{points:[P(0,0),P(100,0)],thickness:5},{points:[P(100,0),P(100,100)],thickness:5},{points:[P(100,100),P(0,100)],thickness:5},{points:[P(0,100),P(0,0)],thickness:5}],4);
console.log('4 separate walls', graphStats(g), findFaces(g,10).map(f=>f.area));
g=buildGraph([{points:sq(0,0,200),thickness:5},{points:[P(100,-20),P(100,220)],thickness:5}],4);
let faces=findFaces(g,10);
console.log('square split by crossing wall', graphStats(g), faces.map(f=>f.area), faces.map(f=>faceInfo(g,f).perimeter));
g=buildGraph([{points:[P(0,0),P(100,0),P(100,100),P(0,100),P(0,0)],thickness:5},{points:[P(100,50),P(180,50)],thickness:5}],4);
console.log('dangling', graphStats(g), findFaces(g,10).map(f=>f.area));
g=buildGraph([{points:sq(0,0,100),thickness:5},{points:sq(100,0,100),thickness:5}],4);
console.log('two squares sharing a side (overlap dedupe)', graphStats(g), findFaces(g,10).map(f=>f.area));
const w=[{points:[P(0,0),P(100,0)],thickness:5,layer:'walls'},{points:[P(100,0),P(100,100)],thickness:5,layer:'walls'},{points:[P(100,100),P(0,100)],thickness:5,layer:'walls'},{points:[P(0,50),P(50,50)],thickness:5,layer:'walls'}];
const m=mergeChains(w,4);
console.log('merge', m.map(c=>({members:c.members,pts:c.points.length})));
const w2=[{points:[P(0,0),P(100,0)],thickness:5,layer:'walls'},{points:[P(100,0),P(100,100)],thickness:5,layer:'walls'},{points:[P(100,0),P(200,0)],thickness:5,layer:'walls'}];
console.log('T junction blocks merge', mergeChains(w2,4).length);
