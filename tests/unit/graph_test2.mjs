import { buildGraph, findFaces, findOuterBoundaries, pointInPolygon, chainsFromGraph } from './wallgraph.mjs';
const P=(x,y)=>({x,y});
const sq=(x,y,s)=>[P(x,y),P(x+s,y),P(x+s,y+s),P(x,y+s),P(x,y)];
let w=[{points:sq(0,0,300),thickness:5,layer:'walls'},{points:sq(100,100,100),thickness:5,layer:'walls'}];
let g=buildGraph(w,1.5);
console.log('faces',findFaces(g,10).map(f=>f.area),'outers',findOuterBoundaries(g,10).map(f=>f.area));
const outs=findOuterBoundaries(g,10);
const inner=outs.find(o=>o.area>-20000);
console.log('inner outer vertex inside big face?',pointInPolygon(inner.points[0], findFaces(g,10).find(f=>f.area>50000).points));
w=[{points:[P(0,0),P(100,0)],thickness:5,layer:'walls'},{points:[P(100,0),P(100,100)],thickness:5,layer:'walls'},{points:[P(50,-50),P(50,50)],thickness:5,layer:'walls'},{points:[P(0,200),P(100,200)],thickness:8,layer:'walls'}];
g=buildGraph(w,1.5);
const ch=chainsFromGraph(g,w);
console.log('chains',ch.map(c=>({n:c.points.length,t:c.thickness})));
w=[{points:sq(0,0,100),thickness:5,layer:'walls'},{points:[P(100,50),P(200,50)],thickness:5,layer:'walls'}];
g=buildGraph(w,1.5);
console.log('square+branch chains',chainsFromGraph(g,w).map(c=>c.points.length));
w=[{points:sq(0,0,100),thickness:5,layer:'walls'}];
g=buildGraph(w,1.5);
console.log('closed loop chains',chainsFromGraph(g,w).map(c=>[c.points.length, c.points[0].x===c.points[c.points.length-1].x]));
