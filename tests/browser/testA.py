from playwright.sync_api import sync_playwright
import json
with sync_playwright() as p:
    b=p.chromium.launch()
    ctx=b.new_context(viewport={'width':1280,'height':900},accept_downloads=True)
    pg=ctx.new_page()
    errs=[]
    pg.on('console',lambda m: errs.append(m.text) if m.type=='error' else None)
    pg.on('pageerror',lambda e: errs.append(str(e)))
    pg.on('dialog',lambda d:d.accept(d.default_value or 'Ground'))
    pg.goto('http://localhost:8765/index.html'); pg.wait_for_timeout(700)
    box=pg.locator('canvas.upper-canvas').first.bounding_box()
    def room(x,y,w,h):
        pg.click('#rect-tool-btn'); pg.mouse.move(box['x']+x,box['y']+y); pg.mouse.down(); pg.mouse.move(box['x']+x+w,box['y']+y+h,steps=5); pg.mouse.up(); pg.mouse.click(box['x']+x+w,box['y']+y+h); pg.wait_for_timeout(300)
    room(200,200,200,120)
    pg.click('#wall-tool-btn')
    for pt in [(500,200),(700,200),(700,350)]:
        pg.mouse.click(box['x']+pt[0],box['y']+pt[1]); pg.wait_for_timeout(100)
    pg.mouse.dblclick(box['x']+700,box['y']+350); pg.wait_for_timeout(300)
    pg.click('#select-tool-btn'); pg.wait_for_timeout(200)
    print('history labels',pg.evaluate("[...document.querySelectorAll('.history-item')].map(e=>e.textContent)"))
    pg.click('#add-floor-btn'); pg.wait_for_timeout(600)
    print('floors',pg.evaluate("[...document.querySelectorAll('.floor-item')].map(e=>e.textContent.trim()+(e.classList.contains('active')?'*':''))"))
    print('history on floor2',pg.evaluate("[...document.querySelectorAll('.history-item')].map(e=>e.textContent)"))
    room(300,300,150,150)
    pg.screenshot(path='/tmp/t/A_floor2.png')
    pg.click('.floor-item:first-child'); pg.wait_for_timeout(600)
    print('back to floor1 history',pg.evaluate("[...document.querySelectorAll('.history-item')].map(e=>e.textContent)"))
    pg.click('#file-menu-btn')
    with pg.expect_download() as d: pg.click('#save-btn')
    path='/tmp/t/floors.gncad'; d.value.save_as(path)
    data=json.load(open(path)); print('meta floors',[(f['name'],f['json'] is None) for f in data['meta']['floors']],'active',data['meta']['activeFloorId'],'canvas objs',len(data['canvasData']['objects']))
    pg.click('#file-menu-btn'); pg.click('#new-btn'); pg.wait_for_timeout(400)
    print('after new floors',pg.locator('.floor-item').count())
    pg.set_input_files('#file-input',path); pg.wait_for_timeout(800)
    print('after load floors',pg.locator('.floor-item').count())
    pg.click('.floor-item:nth-child(2)'); pg.wait_for_timeout(600)
    pg.screenshot(path='/tmp/t/A_loaded_floor2.png')
    pg.click('.floor-item:nth-child(2) .floor-dup'); pg.wait_for_timeout(600)
    print('after dup',pg.locator('.floor-item').count())
    pg.click('.floor-item:nth-child(3) .floor-del'); pg.wait_for_timeout(600)
    print('after del',pg.locator('.floor-item').count())
    pg.click('#undo-btn'); pg.wait_for_timeout(300)
    pg.click('.history-item:first-child'); pg.wait_for_timeout(500)
    print('jump first; labels',pg.evaluate("[...document.querySelectorAll('.history-item')].map(e=>e.textContent+(e.classList.contains('future')?'~':''))"))
    pg.screenshot(path='/tmp/t/A_history.png')
    print('errs',errs)
    b.close()
