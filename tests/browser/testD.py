from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b=p.chromium.launch()
    ctx=b.new_context(viewport={'width':1280,'height':900},accept_downloads=True)
    pg=ctx.new_page(); errs=[]
    pg.on('console',lambda m: errs.append(m.text) if m.type=='error' else None)
    pg.on('pageerror',lambda e: errs.append(str(e)))
    pg.on('dialog',lambda d:d.accept(d.default_value or 'Upper'))
    pg.goto('http://localhost:8765/index.html'); pg.wait_for_timeout(700)
    box=pg.locator('canvas.upper-canvas').first.bounding_box()
    def wall(pts):
        pg.click('#wall-tool-btn'); pg.wait_for_timeout(80)
        for x,y in pts:
            pg.mouse.move(box['x']+x,box['y']+y); pg.mouse.click(box['x']+x,box['y']+y); pg.wait_for_timeout(100)
        pg.click('#select-tool-btn'); pg.wait_for_timeout(250)
    wall([(200,200),(500,200)]); wall([(500,200),(500,400)]); wall([(500,400),(200,400)]); wall([(200,400),(200,200)])
    pg.click('#graph-tool-btn'); pg.click('#graph-rooms-btn'); pg.wait_for_timeout(300); pg.click('#close-graph-modal-btn')
    print('area before:',pg.evaluate("1"))
    pg.click('#node-tool-btn'); pg.wait_for_timeout(200)
    pg.mouse.move(box['x']+500,box['y']+200); pg.mouse.down()
    for k in range(1,6): pg.mouse.move(box['x']+500+10*k,box['y']+200-10*k); pg.wait_for_timeout(40)
    pg.mouse.up(); pg.wait_for_timeout(300)
    print('tip',pg.inner_text('#tool-tip'))
    print('labels',[e.text_content() for e in pg.locator('.history-item').all()][-3:])
    pg.screenshot(path='/tmp/t/D_node.png')
    pg.click('#graph-tool-btn'); pg.wait_for_timeout(200)
    print(pg.inner_text('#graph-summary').replace('\n',' | ')); pg.click('#close-graph-modal-btn')
    pg.click('#undo-btn'); pg.wait_for_timeout(300)
    pg.click('#graph-tool-btn'); pg.wait_for_timeout(200)
    print('after undo',pg.inner_text('#graph-summary').replace('\n',' | ')[-120:]); pg.click('#close-graph-modal-btn')
    pg.click('#redo-btn'); pg.wait_for_timeout(300)
    pg.click('#theme-toggle-btn'); pg.wait_for_timeout(400)
    pg.screenshot(path='/tmp/t/D_light.png')
    pg.click('#theme-toggle-btn'); pg.wait_for_timeout(300)
    pg.click('#add-floor-btn'); pg.wait_for_timeout(600)
    pg.check('#ghost-floor-toggle'); pg.wait_for_timeout(600)
    pg.screenshot(path='/tmp/t/D_ghost.png')
    pg.click('#theme-toggle-btn'); pg.wait_for_timeout(500)
    pg.screenshot(path='/tmp/t/D_ghost_light.png')
    print('errs',errs); b.close()
