from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':1280,'height':860}); pg=ctx.new_page(); errs=[]
    pg.on('pageerror',lambda e: errs.append(str(e))); pg.on('console',lambda m: errs.append(m.text) if m.type=='error' else None)
    pg.on('dialog',lambda d:d.accept('X'))
    pg.goto('http://localhost:8765/index.html'); pg.wait_for_timeout(700)
    box=pg.locator('canvas.upper-canvas').first.bounding_box()
    pg.click('#wall-tool-btn')
    for x,y in [(200,200),(520,200),(520,420),(200,420),(200,200)]:
        pg.mouse.move(box['x']+x,box['y']+y); pg.mouse.click(box['x']+x,box['y']+y); pg.wait_for_timeout(90)
    pg.click('#select-tool-btn'); pg.wait_for_timeout(200)
    pg.click('#graph-tool-btn'); pg.click('#graph-rooms-btn'); pg.wait_for_timeout(300); pg.click('#close-graph-modal-btn')
    pg.click('#door-tool-btn'); pg.mouse.move(box['x']+360,box['y']+200); pg.wait_for_timeout(100); pg.mouse.click(box['x']+360,box['y']+200); pg.wait_for_timeout(300)
    pg.click('#window-tool-btn'); pg.mouse.move(box['x']+520,box['y']+300); pg.wait_for_timeout(100); pg.mouse.click(box['x']+520,box['y']+300); pg.wait_for_timeout(300)
    pg.click('#asset-tool-btn'); pg.wait_for_timeout(300)
    pg.click('.asset-item[title="L-Shaped Sofa"]'); pg.mouse.click(box['x']+300,box['y']+330); pg.wait_for_timeout(500)
    pg.click('.asset-item[title="Car"]'); pg.mouse.click(box['x']+700,box['y']+300); pg.wait_for_timeout(500)
    pg.click('#select-tool-btn'); pg.mouse.click(box['x']+400,box['y']+300); pg.wait_for_timeout(300)
    for pat in ['wood','brick','checker','concrete']:
        sel=pg.locator('select').filter(has=pg.locator('option[value="wood"]'))
        sel.select_option(pat); pg.wait_for_timeout(200)
        pg.screenshot(path=f'/tmp/t/N_pat_{pat}.png', clip={'x':box['x']+190,'y':box['y']+190,'width':350,'height':250})
    pg.click('#settings-btn'); pg.select_option('[data-key="units"]','imperial'); pg.wait_for_timeout(200); pg.select_option('[data-key="language"]','fa'); pg.wait_for_timeout(300); pg.screenshot(path='/tmp/t/N_settings_imperial_fa.png'); pg.click('#close-settings-modal-btn')
    pg.click('#fillet-tool-btn'); pg.wait_for_timeout(200)
    print('fillet label:', pg.inner_text('label[for="fillet-radius"]'), '| value', pg.input_value('#fillet-radius'))
    pg.fill('#fillet-radius','2'); pg.click('#fillet-apply-btn'); pg.wait_for_timeout(200)
    pg.mouse.click(box['x']+520,box['y']+200); pg.wait_for_timeout(300)
    print('tip:', pg.inner_text('#tool-tip'))
    pg.click('#settings-btn'); pg.select_option('[data-key="units"]','metric'); pg.select_option('[data-key="language"]','en'); pg.click('#close-settings-modal-btn')
    print('stored fillet radius (m) roundtrip input:', end=' '); pg.click('#fillet-tool-btn'); print(pg.input_value('#fillet-radius'), pg.inner_text('label[for="fillet-radius"]')); pg.click('#close-fillet-modal-btn')
    pg.click('#select-tool-btn'); pg.click('#file-menu-btn'); pg.click('#view3d-btn'); pg.wait_for_timeout(900)
    pg.mouse.move(640,400); pg.mouse.down(); pg.mouse.move(600,380,steps=5); pg.mouse.up(); pg.wait_for_timeout(300)
    pg.screenshot(path='/tmp/t/N_3d.png')
    print('errs',errs); b.close()
