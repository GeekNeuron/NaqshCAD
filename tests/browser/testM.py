from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b=p.chromium.launch()
    ctx=b.new_context(viewport={'width':390,'height':780},has_touch=True,is_mobile=True,device_scale_factor=2)
    pg=ctx.new_page(); errs=[]
    pg.on('pageerror',lambda e: errs.append(str(e)))
    pg.on('dialog',lambda d:d.accept(d.default_value or 'X'))
    pg.goto('http://localhost:8765/index.html'); pg.wait_for_timeout(900)
    pg.screenshot(path='/tmp/t/M_main.png')
    print('toolbar', pg.evaluate("(()=>{const t=document.getElementById('left-toolbar');const r=t.getBoundingClientRect();return {top:r.top,h:r.height,w:r.width,scrollW:t.scrollWidth,dir:getComputedStyle(t).flexDirection}})()"))
    print('canvas vs container', pg.evaluate("(()=>{const c=document.getElementById('canvas-container');const cv=document.querySelector('canvas.lower-canvas');return [c.offsetWidth,c.offsetHeight,cv.width/ (window.devicePixelRatio||1),cv.height/(window.devicePixelRatio||1)]})()"))
    pg.click('#wall-tool-btn'); pg.wait_for_timeout(300)
    pg.screenshot(path='/tmp/t/M_wall_popover.png')
    pg.click('#select-tool-btn')
    pg.click('#settings-btn'); pg.wait_for_timeout(400)
    pg.screenshot(path='/tmp/t/M_settings.png')
    pg.click('#close-settings-modal-btn')
    pg.click('#panel-toggle-btn'); pg.wait_for_timeout(500)
    pg.screenshot(path='/tmp/t/M_panel.png')
    pg.mouse.click(8,300); pg.wait_for_timeout(500)
    pg.set_viewport_size({'width':780,'height':390}); pg.wait_for_timeout(700)
    print('landscape canvas vs container', pg.evaluate("(()=>{const c=document.getElementById('canvas-container');const cv=document.querySelector('canvas.lower-canvas');const dpr=window.devicePixelRatio||1;return [c.offsetWidth,c.offsetHeight,Math.round(cv.width/dpr),Math.round(cv.height/dpr)]})()"))
    pg.screenshot(path='/tmp/t/M_landscape.png')
    pg.set_viewport_size({'width':390,'height':780}); pg.wait_for_timeout(500)
    pg.click('#settings-btn'); pg.check('[data-key="largeTargets"]'); pg.wait_for_timeout(300); pg.click('#close-settings-modal-btn'); pg.wait_for_timeout(400)
    pg.screenshot(path='/tmp/t/M_large.png')
    print('errs',errs); b.close()
