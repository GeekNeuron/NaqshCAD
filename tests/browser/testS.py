    with pg.expect_download() as d: pg.click('[data-action="exportSettings"]')
    d.value.save_as('/tmp/t/settings.json'); print('exported', json.load(open('/tmp/t/settings.json'))['theme'])
    pg.click('[data-action="resetSettings"]'); pg.wait_for_timeout(300)
    print('after reset theme', pg.evaluate("document.body.className"), 'select', pg.input_value('[data-key="theme"]'))
    pg.set_input_files('#settings-file-input','/tmp/t/settings.json'); pg.wait_for_timeout(400)
