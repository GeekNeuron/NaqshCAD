from playwright.sync_api import sync_playwright
import json
with sync_playwright() as p:
    b=p.chromium.launch()
    ctx=b.new_context(viewport={'width':1280,'height':900},accept_downloads=True)
    pg=ctx.new_page()
    errs=[]
    pg.on('console',lambda m: errs.append(m.text) if m.type=='error' else None)
    pg.on('pageerror',lambda e: errs.append(str(e)))
    pg.on('dialog',lambda d:d.accept(d.default_value or 'X'))
    pg.goto('http://localhost:8765/index.html'); pg.wait_for_timeout(700)
    box=pg.locator('canvas.upper-canvas').first.bounding_box()
    def wall(pts):
        pg.click('#wall-tool-btn'); pg.wait_for_timeout(100)
        for x,y in pts:
            pg.mouse.move(box['x']+x,box['y']+y); pg.mouse.click(box['x']+x,box['y']+y); pg.wait_for_timeout(120)
        pg.keyboard.press('Enter'); pg.wait_for_timeout(300)
    wall([(200,200),(500,200),(500,400),(250,420)])
    pg.click('#select-tool-btn')
    print('labels',[e.text_content() for e in pg.locator('.history-item').all()])
    pg.screenshot(path='/tmp/t/B_wall.png')
    pg.click('#fillet-tool-btn'); pg.wait_for_timeout(200)
    print('modal visible',pg.is_visible('#fillet-modal'))
    pg.fill('#fillet-radius','0.8'); pg.click('#fillet-apply-btn'); pg.wait_for_timeout(200)
    pg.mouse.click(box['x']+500,box['y']+200); pg.wait_for_timeout(400)
    print('tip',pg.inner_text('#tool-tip'))
    pg.mouse.click(box['x']+500,box['y']+400); pg.wait_for_timeout(400)
    print('tip',pg.inner_text('#tool-tip'))
    pg.screenshot(path='/tmp/t/B_filleted.png')
    pg.click('#select-tool-btn'); pg.wait_for_timeout(200)
    pg.mouse.click(box['x']+350,box['y']+200); pg.wait_for_timeout(400)
    print('panel buttons',pg.evaluate("[...document.querySelectorAll('#panel-content button')].map(b=>b.textContent.trim())"))
    print('labels',[e.text_content() for e in pg.locator('.history-item').all()])
    pg.click('text=Revert Last Fillet'); pg.wait_for_timeout(400)
    pg.screenshot(path='/tmp/t/B_reverted1.png')
    print('panel buttons',pg.evaluate("[...document.querySelectorAll('#panel-content button')].map(b=>b.textContent.trim())"))
    pg.click('text=Revert Last Fillet'); pg.wait_for_timeout(400)
    print('panel buttons after 2nd revert',pg.evaluate("[...document.querySelectorAll('#panel-content button')].map(b=>b.textContent.trim())"))
    pg.screenshot(path='/tmp/t/B_reverted2.png')
    pg.click('#file-menu-btn')
    with pg.expect_download() as d: pg.click('#export-dxf-btn')
    d.value.save_as('/tmp/t/out.dxf'); print('dxf bytes',len(open('/tmp/t/out.dxf').read()))
    print('errs',errs)
    b.close()
