from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b=p.chromium.launch()
    ctx=b.new_context(viewport={'width':1280,'height':900},accept_downloads=True)
    pg=ctx.new_page(); errs=[]
    pg.on('console',lambda m: errs.append(m.text) if m.type=='error' else None)
    pg.on('pageerror',lambda e: errs.append(str(e)))
    pg.on('dialog',lambda d:d.accept(d.default_value or 'X'))
    pg.goto('http://localhost:8765/index.html'); pg.wait_for_timeout(700)
    box=pg.locator('canvas.upper-canvas').first.bounding_box()
    def wall(pts):
        pg.click('#wall-tool-btn'); pg.wait_for_timeout(80)
        for x,y in pts:
            pg.mouse.move(box['x']+x,box['y']+y); pg.mouse.click(box['x']+x,box['y']+y); pg.wait_for_timeout(100)
        pg.click('#select-tool-btn'); pg.wait_for_timeout(250)
    def print_labels(): print('after 4 walls',[e.text_content() for e in pg.locator('.history-item').all()])
    wall([(200,200),(500,200)]); wall([(500,200),(500,400)]); wall([(500,400),(200,400)]); wall([(200,400),(200,200)]); print_labels()
    wall([(350,150),(350,450)])
    pg.click('#select-tool-btn')
    pg.click('#graph-tool-btn'); pg.wait_for_timeout(300)
    print('SUMMARY1', pg.inner_text('#graph-summary').replace('\n',' | '))
    pg.screenshot(path='/tmp/t/C_modal1.png')
    pg.click('#graph-merge-btn'); pg.wait_for_timeout(300)
    print('MERGE', pg.inner_text('#graph-message'))
    pg.click('#graph-rooms-btn'); pg.wait_for_timeout(400)
    print('ROOMS', pg.inner_text('#graph-message'))
    print('SUMMARY2', pg.inner_text('#graph-summary').replace('\n',' | '))
    pg.click('#graph-rooms-btn'); pg.wait_for_timeout(300)
    print('AGAIN', pg.inner_text('#graph-message'))
    pg.screenshot(path='/tmp/t/C_modal2.png')
    pg.click('#close-graph-modal-btn'); pg.wait_for_timeout(200)
    pg.screenshot(path='/tmp/t/C_plan.png')
    print('labels',[e.text_content() for e in pg.locator('.history-item').all()])
    pg.click('.history-item:nth-last-child(3)'); pg.wait_for_timeout(400)
    pg.screenshot(path='/tmp/t/C_jumpback.png')
    print('errs',errs); b.close()
