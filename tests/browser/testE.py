from playwright.sync_api import sync_playwright
import re
with sync_playwright() as p:
    b=p.chromium.launch()
    ctx=b.new_context(viewport={'width':1280,'height':900},accept_downloads=True)
    pg=ctx.new_page(); errs=[]
    pg.on('console',lambda m: errs.append(m.text) if m.type=='error' else None)
    pg.on('pageerror',lambda e: errs.append(str(e)))
    pg.on('dialog',lambda d:d.accept(d.default_value or 'Upper'))
    pg.goto('http://localhost:8765/index.html'); pg.wait_for_timeout(700)
    pg.evaluate("window.__printed=0; window.print=()=>{window.__printed++}")
    box=pg.locator('canvas.upper-canvas').first.bounding_box()
    def wall(pts):
        pg.click('#wall-tool-btn'); pg.wait_for_timeout(80)
        for x,y in pts:
            pg.mouse.move(box['x']+x,box['y']+y); pg.mouse.click(box['x']+x,box['y']+y); pg.wait_for_timeout(90)
        pg.click('#select-tool-btn'); pg.wait_for_timeout(250)
    wall([(120,120),(520,120),(520,420),(120,420),(120,120)])
    wall([(260,220),(380,220),(380,320),(260,320),(260,220)])
    pg.click('#graph-tool-btn'); pg.wait_for_timeout(200)
    pg.click('#graph-rooms-btn'); pg.wait_for_timeout(400)
    print('ROOMS', pg.inner_text('#graph-message')); print(pg.inner_text('#graph-summary').replace('\n',' | '))
    pg.screenshot(path='/tmp/t/E_holes_modal.png')
    pg.click('#close-graph-modal-btn'); pg.wait_for_timeout(200)
    pg.screenshot(path='/tmp/t/E_holes.png')
    pg.click('#graph-tool-btn'); pg.wait_for_timeout(200)
    pg.click('#graph-normalize-btn'); pg.wait_for_timeout(300); print('NORM', pg.inner_text('#graph-message'))
    pg.check('#graph-auto-toggle'); pg.click('#close-graph-modal-btn')
    wall([(600,100),(600,300)]); wall([(560,200),(700,200)])
    pg.click('#graph-tool-btn'); pg.wait_for_timeout(200)
    print('after auto', pg.inner_text('#graph-summary').replace('\n',' | ')[:230]); pg.click('#close-graph-modal-btn')
    pg.click('#add-floor-btn'); pg.wait_for_timeout(500)
    wall([(150,150),(450,150),(450,350)])
    pg.click('#file-menu-btn')
    with pg.expect_download() as d: pg.click('#export-all-dxf-btn')
    d.value.save_as('/tmp/t/all.dxf'); s=open('/tmp/t/all.dxf').read()
    print('layers', re.findall(r'LAYER\n2\n(\S+)\n70\n0\n62', s), 'LINE count', s.count('\nLINE\n'), 'LWPOLY', s.count('LWPOLYLINE'))
    pg.click('#file-menu-btn'); pg.click('#print-btn'); pg.wait_for_timeout(300)
    pg.check('#print-all-floors'); pg.select_option('#print-scale','100'); pg.click('#print-apply-btn'); pg.wait_for_timeout(1500)
    print('print: imgs', pg.evaluate("document.querySelectorAll('#print-container img').length"), 'printed', pg.evaluate("window.__printed"), 'multi', pg.evaluate("document.body.classList.contains('printing-multi')"))
    print('errs',errs); b.close()
